  /// Helper to get random template based on language
  static String _getRandomTemplate(Map<String, List<String>> templates, String lang) {
    final list = templates[lang] ?? templates['en'] ?? <String>[];
    if (list.isEmpty) {
      return 'I am not sure I understand. Can you please explain?';
    }
    return list[Random().nextInt(list.length)];
  }
