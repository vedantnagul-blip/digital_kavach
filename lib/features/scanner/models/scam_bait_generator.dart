import 'dart:math';

/// Fallback heuristic templates for ScamBaiter when Gemma is not available
/// Supports ALL 10 Indian languages: en, hi, mr, ta, te, bn, gu, kn, ml, pa
class ScamBaitGenerator {
  /// Generate a decoy reply based on scam type and language
  static String generateBaitReply(String scamText, {String lang = 'en'}) {
    final scamType = _detectScamType(scamText);
    final normalizedLang = _normalizeLang(lang);

    switch (scamType) {
      case ScamType.digitalArrest:
        return _getDigitalArrestBait(normalizedLang);
      case ScamType.electricityBill:
        return _getElectricityBillBait(normalizedLang);
      case ScamType.kyc:
        return _getKycBait(normalizedLang);
      case ScamType.upi:
        return _getUpiBait(normalizedLang);
      case ScamType.lottery:
        return _getLotteryBait(normalizedLang);
      case ScamType.generic:
      default:
        return _getGenericBait(normalizedLang);
    }
  }

  /// Normalize language code to supported languages
  static String _normalizeLang(String lang) {
    const langMap = {
      'en': 'en', 'English': 'en', 'english': 'en',
      'hi': 'hi', 'Hindi': 'hi', 'hindi': 'hi', 'हिंदी': 'hi',
      'mr': 'mr', 'Marathi': 'mr', 'marathi': 'mr', 'मराठी': 'mr',
      'ta': 'ta', 'Tamil': 'ta', 'tamil': 'ta', 'தமிழ்': 'ta',
      'te': 'te', 'Telugu': 'te', 'telugu': 'te', 'తెలుగు': 'te',
      'bn': 'bn', 'Bengali': 'bn', 'bengali': 'bn', 'বাংলা': 'bn',
      'gu': 'gu', 'Gujarati': 'gu', 'gujarati': 'gu', 'ગુજરાતી': 'gu',
      'kn': 'kn', 'Kannada': 'kn', 'kannada': 'kn', 'ಕನ್ನಡ': 'kn',
      'ml': 'ml', 'Malayalam': 'ml', 'malayalam': 'ml', 'മലയാളം': 'ml',
      'pa': 'pa', 'Punjabi': 'pa', 'punjabi': 'pa', 'ਪੰਜਾਬੀ': 'pa',
    };
    return langMap[lang] ?? 'en';
  }

  /// Detect scam type from text (fallback heuristic)
  static ScamType _detectScamType(String text) {
    final lowerText = text.toLowerCase();

    // Digital Arrest - Multi-language keywords
    if (lowerText.contains('digital arrest') ||
        lowerText.contains('cbi') ||
        lowerText.contains('police') ||
        lowerText.contains('arrest') ||
        lowerText.contains('court') ||
        lowerText.contains('video call') ||
        lowerText.contains('skype') ||
        lowerText.contains('డిజిటల్ అरेస్ట') ||
        lowerText.contains('పులీస్') ||
        lowerText.contains('அரெஸ்ட்') ||
        lowerText.contains('পুলিশ') ||
        lowerText.contains('પોલીસ') ||
        lowerText.contains('ಪೋಲೀಸ್') ||
        lowerText.contains('പോലീസ്') ||
        lowerText.contains('गिरफ्तारी') ||
        lowerText.contains('डिजिटल अरेस्ट')) {
      return ScamType.digitalArrest;
    }

    // Electricity Bill - Multi-language keywords
    if (lowerText.contains('electricity') ||
        lowerText.contains('mahavitaran') ||
        lowerText.contains('bill') ||
        lowerText.contains('disconnect') ||
        lowerText.contains('power') ||
        lowerText.contains('current') ||
        lowerText.contains('वीज') ||
        lowerText.contains('बिजली') ||
        lowerText.contains('மின்சாரம்') ||
        lowerText.contains('విద్యుత్') ||
        lowerText.contains('বিদ্যুৎ') ||
        lowerText.contains('વીજ') ||
        lowerText.contains('ವಿದ್ಯುತ್') ||
        lowerText.contains('മിന്‍സാരം') ||
        lowerText.contains('बिजली') ||
        lowerText.contains('ಮಹಾವಿತರಣ')) {
      return ScamType.electricityBill;
    }

    // KYC - Multi-language keywords
    if (lowerText.contains('kyc') ||
        lowerText.contains('update') ||
        lowerText.contains('verify') ||
        lowerText.contains('aadhaar') ||
        lowerText.contains('pan') ||
        lowerText.contains('expired') ||
        lowerText.contains('कवच') ||
        lowerText.contains('अधार') ||
        lowerText.contains('பான்') ||
        lowerText.contains('KYC') ||
        lowerText.contains('কেওয়াইসি') ||
        lowerText.contains('કેવાયસી') ||
        lowerText.contains('ಕೆವೈಸಿ') ||
        lowerText.contains('kevaic') ||
        lowerText.contains('केवाईसी')) {
      return ScamType.kyc;
    }

    // UPI - Multi-language keywords
    if (lowerText.contains('upi') ||
        lowerText.contains('phonepe') ||
        lowerText.contains('gpay') ||
        lowerText.contains('paytm') ||
        lowerText.contains('reward') ||
        lowerText.contains('cashback') ||
        lowerText.contains('received rs') ||
        lowerText.contains('yono') ||
        lowerText.contains('भुगतान') ||
        lowerText.contains('பணம்') ||
        lowerText.contains('పేమెంట్') ||
        lowerText.contains('પેમેન્ટ') ||
        lowerText.contains('ಪೇಮೆಂಟ್') ||
        lowerText.contains('പേമെന്റ്') ||
        lowerText.contains('भुगतान') ||
        lowerText.contains('పేమెంటు')) {
      return ScamType.upi;
    }

    // Lottery - Multi-language keywords
    if (lowerText.contains('lottery') ||
        lowerText.contains('prize') ||
        lowerText.contains('won') ||
        lowerText.contains('jackpot') ||
        lowerText.contains('lucky') ||
        lowerText.contains('लॉटरी') ||
        lowerText.contains('इनाम') ||
        lowerText.contains('லாட்டரி') ||
        lowerText.contains('பரிசு') ||
        lowerText.contains('లాటరీ') ||
        lowerText.contains('લોટરી') ||
        lowerText.contains('ಲಾಟರಿ') ||
        lowerText.contains('ലോട്ടറി') ||
        lowerText.contains('લਾਟਰੀ') ||
        lowerText.contains('इनाम')) {
      return ScamType.lottery;
    }

    return ScamType.generic;
  }

